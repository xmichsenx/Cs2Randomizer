import { test } from 'node:test';
import assert from 'node:assert/strict';
import { encodeCrosshair, decodeCrosshair } from '../js/sharecode.js';
import { randomCrosshair } from '../js/crosshair-random.js';

const base = {
  style: 2, followRecoil: false, centerDotEnabled: true, tStyleEnabled: false, outlineMode: 0,
  red: 255, green: 0, blue: 0, alpha: 255, outlineRed: 0, outlineGreen: 0, outlineBlue: 0, outlineAlpha: 255,
  gap: 0, length: 5, thickness: 1, dynamicSpreadLimit: 181, splitDistance: 3, innerSplitAlpha: 1,
  outerSplitAlpha: 0.35, splitSizeRatio: 0, screenHeight: 768, scopeDotScale: 1, scopeDotUseCrosshairColor: false,
};

// Vectors from akiver/csgo-sharecode; the first three were generated by CS2 1.41.8.8 itself.
const vectors = [
  ['CSvbPubOq37zTGqtsPTP5QTrp5CB4xFXiKRLfzJsm49ZRe', base],
  ['CSoYQNXCQtL5b44fPZKwPPZZCUpsywopyvJW3koh75uFih', { ...base, scopeDotUseCrosshairColor: true }],
  ['CSHt3ObzKS3ikGJLRBVrKjPUrhOCikyke53na8cJFtNZKa', { ...base, scopeDotUseCrosshairColor: true, scopeDotScale: 0.55 }],
  ['CSAB6Oby2JUDOrBRy4jRcsR6JOQdhbszKF9GuKQGhKVwAc', {
    style: 9, followRecoil: true, centerDotEnabled: false, tStyleEnabled: true, outlineMode: 2,
    red: 10, green: 20, blue: 30, alpha: 200, outlineRed: 40, outlineGreen: 50, outlineBlue: 60, outlineAlpha: 128,
    gap: -7, length: 255, thickness: 12, dynamicSpreadLimit: 64, splitDistance: 127, innerSplitAlpha: 0.29,
    outerSplitAlpha: 0.97, splitSizeRatio: 0.63, screenHeight: 1440, scopeDotScale: 2, scopeDotUseCrosshairColor: true,
  }],
];

test('encodes reference vectors exactly', () => {
  for (const [code, xhair] of vectors) assert.equal(encodeCrosshair(xhair), code);
});

test('decodes reference vectors exactly', () => {
  for (const [code, xhair] of vectors) assert.deepEqual(decodeCrosshair(code), xhair);
});

test('rejects bad codes', () => {
  for (const bad of [
    'CSuZhVyU8icUwjTjopBSVi6ctEbq5GiOXJBRdC6LNLKaFL', // unknown version
    'CSkSCHQKunGr2yPsJr2U3RTd8ycMA2pEs9jWnxK5KjMmWL', // bad checksum
    'CSoQhciXBHZUKAbfexZBeMWFKxkrXL5MLumDLj3JYW4snP', // screen height 0
    'CSGO-O4Jsi-V36wY-rTMGK-9w7qF-jQ8WB',
    'hello',
  ]) assert.throws(() => decodeCrosshair(bad));
});

test('random crosshairs round-trip through the share code', () => {
  for (const mode of ['sane', 'chaos']) {
    for (let i = 0; i < 5000; i++) {
      const x = randomCrosshair({ mode, screenHeight: 1080 });
      const code = encodeCrosshair(x);
      assert.match(code, /^CS[A-HJ-Za-fh-km-z2-9]{44}$/);
      assert.deepEqual(decodeCrosshair(code), x);
    }
  }
});
